-- The schema invariants Gifty relies on, rather than a restatement of every column.
begin;
create extension if not exists pgtap with schema extensions;
select plan(69);

-- Tables in scope, and Android-local concepts that must not exist on the server.
select tables_are('public', array['profiles', 'people', 'occasions', 'gift_ideas', 'gifts', 'sync_mutations'],
    'public holds exactly the synced tables, profiles and the mutation ledger');
select hasnt_table('public', 'sync_operations', 'the sync queue is Android-local');
select hasnt_column('public', 'people', 'remote_state', 'remote state is Android-local');

-- Enums carry exactly the Android values.
select enum_has_labels('public', 'occasion_type', array['BIRTHDAY', 'NAME_DAY', 'ANNIVERSARY', 'CHRISTMAS', 'CUSTOM']);
select enum_has_labels('public', 'gift_idea_status', array['IDEA', 'PLANNED', 'PURCHASED']);
select enum_has_labels('public', 'gift_direction', array['GIVEN', 'RECEIVED']);

-- Ids are uuid primary keys generated by the client, never by the server.
select col_is_pk('public', 'people', 'id', 'people.id is the primary key');
select col_is_pk('public', 'occasions', 'id', 'occasions.id is the primary key');
select col_is_pk('public', 'gift_ideas', 'id', 'gift_ideas.id is the primary key');
select col_is_pk('public', 'gifts', 'id', 'gifts.id is the primary key');
select col_type_is('public', 'people', 'id', 'uuid', 'people.id is uuid');
select col_hasnt_default('public', 'people', 'id', 'people.id has no server default: the client generates ids');
select col_hasnt_default('public', 'occasions', 'id', 'occasions.id has no server default: the client generates ids');
select col_hasnt_default('public', 'gift_ideas', 'id', 'gift_ideas.id has no server default: the client generates ids');
select col_hasnt_default('public', 'gifts', 'id', 'gifts.id has no server default: the client generates ids');

-- Sync metadata on every synced table.
select col_type_is('public', 'people', 'version', 'bigint', 'people.version is bigint');
select col_default_is('public', 'people', 'version', '1', 'people.version defaults to 1');
select has_column('public', 'people', 'deleted_at', 'people has deleted_at');
select has_column('public', 'occasions', 'deleted_at', 'occasions has deleted_at');
select has_column('public', 'gift_ideas', 'deleted_at', 'gift_ideas has deleted_at');
select has_column('public', 'gifts', 'deleted_at', 'gifts has deleted_at');
select has_column('public', 'gift_ideas', 'archived_at', 'gift_ideas has archived_at');
select col_type_is('public', 'gifts', 'given_at', 'date', 'gifts.given_at is date');
select col_type_is('public', 'gifts', 'price_amount_minor', 'bigint', 'gifts.price_amount_minor is bigint');

-- References stay within one owner: composite foreign keys over (id, owner_user_id).
select fk_ok('public', 'occasions', array['person_id', 'owner_user_id'], 'public', 'people', array['id', 'owner_user_id']);
select fk_ok('public', 'gift_ideas', array['recipient_person_id', 'owner_user_id'], 'public', 'people', array['id', 'owner_user_id']);
select fk_ok('public', 'gift_ideas', array['occasion_id', 'owner_user_id'], 'public', 'occasions', array['id', 'owner_user_id']);
select fk_ok('public', 'gifts', array['giver_person_id', 'owner_user_id'], 'public', 'people', array['id', 'owner_user_id']);
select fk_ok('public', 'gifts', array['recipient_person_id', 'owner_user_id'], 'public', 'people', array['id', 'owner_user_id']);
select fk_ok('public', 'gifts', array['occasion_id', 'owner_user_id'], 'public', 'occasions', array['id', 'owner_user_id']);
select fk_ok('public', 'gifts', array['source_gift_idea_id', 'owner_user_id'], 'public', 'gift_ideas', array['id', 'owner_user_id']);

-- No foreign key between domain rows erases history on delete.
select is(
    (select count(*)::int
     from pg_constraint
     where contype = 'f'
       and connamespace = 'public'::regnamespace
       and confrelid in ('public.people'::regclass, 'public.occasions'::regclass, 'public.gift_ideas'::regclass)
       and confdeltype <> 'a'),
    0,
    'references between people, occasions, ideas and gifts never cascade');

-- Indexes for the owner-scoped full pull (also serving RLS filters) and reference lookups.
select has_index('public', 'people', 'people_owner_user_id_id_idx', array['owner_user_id', 'id']);
select has_index('public', 'occasions', 'occasions_owner_user_id_id_idx', array['owner_user_id', 'id']);
select has_index('public', 'occasions', 'occasions_person_id_idx', array['person_id']);
select has_index('public', 'gift_ideas', 'gift_ideas_owner_user_id_id_idx', array['owner_user_id', 'id']);
select has_index('public', 'gift_ideas', 'gift_ideas_recipient_person_id_idx', array['recipient_person_id']);
select has_index('public', 'gift_ideas', 'gift_ideas_occasion_id_idx', array['occasion_id']);
select has_index('public', 'gifts', 'gifts_owner_user_id_id_idx', array['owner_user_id', 'id']);
select has_index('public', 'gifts', 'gifts_giver_person_id_idx', array['giver_person_id']);
select has_index('public', 'gifts', 'gifts_recipient_person_id_idx', array['recipient_person_id']);
select has_index('public', 'gifts', 'gifts_occasion_id_idx', array['occasion_id']);
select has_index('public', 'gifts', 'gifts_source_gift_idea_id_key', array['source_gift_idea_id']);

-- Row level security is on everywhere.
select is(
    (select count(*)::int from pg_class
     where relnamespace = 'public'::regnamespace and relkind = 'r' and not relrowsecurity),
    0,
    'every public table has row level security enabled');

-- Grants: authenticated may read, create and update, never delete; anon gets nothing.
select table_privs_are('public', 'people', 'authenticated', array['SELECT', 'INSERT', 'UPDATE']);
select table_privs_are('public', 'occasions', 'authenticated', array['SELECT', 'INSERT', 'UPDATE']);
select table_privs_are('public', 'gift_ideas', 'authenticated', array['SELECT', 'INSERT', 'UPDATE']);
select table_privs_are('public', 'gifts', 'authenticated', array['SELECT', 'INSERT', 'UPDATE']);
select table_privs_are('public', 'profiles', 'authenticated', array['SELECT']);
select table_privs_are('public', 'people', 'anon', array[]::text[]);
select table_privs_are('public', 'occasions', 'anon', array[]::text[]);
select table_privs_are('public', 'gift_ideas', 'anon', array[]::text[]);
select table_privs_are('public', 'gifts', 'anon', array[]::text[]);
select table_privs_are('public', 'profiles', 'anon', array[]::text[]);
-- service_role is granted only the data operations server-side administration needs.
select table_privs_are('public', 'people', 'service_role', array['SELECT', 'INSERT', 'UPDATE', 'DELETE']);
select table_privs_are('public', 'profiles', 'service_role', array['SELECT', 'INSERT', 'UPDATE', 'DELETE']);

-- Every synced row carries the id of the mutation that last wrote it, never defaulted by the server.
select has_column('public', 'people', 'last_mutation_id', 'people have last_mutation_id');
select has_column('public', 'occasions', 'last_mutation_id', 'occasions have last_mutation_id');
select has_column('public', 'gift_ideas', 'last_mutation_id', 'gift ideas have last_mutation_id');
select has_column('public', 'gifts', 'last_mutation_id', 'gifts have last_mutation_id');
select col_hasnt_default('public', 'people', 'last_mutation_id', 'mutation ids come from the client, never a server default');

-- The ledger: readable by its owner, writable by nobody but the recording trigger.
select col_is_pk('public', 'sync_mutations', 'mutation_id', 'a mutation id is recorded at most once');
select table_privs_are('public', 'sync_mutations', 'authenticated', array['SELECT']);
select table_privs_are('public', 'sync_mutations', 'anon', array[]::text[]);
select table_privs_are('public', 'sync_mutations', 'service_role', array['SELECT', 'INSERT', 'UPDATE', 'DELETE']);
select is(
    (select prosecdef from pg_proc where oid = 'private.record_sync_mutation()'::regprocedure),
    true,
    'the ledger is written only by its security definer trigger function');
select is(
    (select proconfig from pg_proc where oid = 'private.record_sync_mutation()'::regprocedure),
    array['search_path=""'],
    'the recording function runs with an empty search_path');

-- Profiles may only have their descriptive columns updated.
select is(
    (select array_agg(column_name::text order by column_name::text)
     from information_schema.column_privileges
     where table_schema = 'public' and table_name = 'profiles'
       and grantee = 'authenticated' and privilege_type = 'UPDATE'),
    array['avatar_path', 'display_name', 'preferred_locale'],
    'authenticated may update only the descriptive profile columns');

-- Internal helpers are not callable by clients.
select is(
    (select count(*)::int
     from pg_proc p
     where p.pronamespace = 'private'::regnamespace
       and (has_function_privilege('authenticated', p.oid, 'execute')
            or has_function_privilege('anon', p.oid, 'execute'))),
    0,
    'no private helper function is executable by client roles');

select * from finish();
rollback;
